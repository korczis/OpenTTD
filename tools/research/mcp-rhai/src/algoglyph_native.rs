//! RESEARCH-ONLY / UNSTABLE: AlgoGlyph's Rust kernels, run in-process (I0227, ADR 0039).
//!
//! AlgoGlyph is a git submodule of this fork, pinned at one commit
//! (`tools/research/vendor/algoglyph`, bumped only by `tools/research/algoglyph-pin bump`), and its
//! crate `algoglyph-kernels` is a path dependency of mcp-rhai. Every kernel of the crate's sorting
//! registry becomes one entry of the discovered kernel catalogue, with engine [`ENGINE`], and is
//! answered here, in this process, instead of by `npm run flow -- kernel`. Nothing names a kernel:
//! the entries are the crate's own registry (`sorting::REGISTRY`, generated by its build script),
//! the input each reads is derived from the options its source reads (`Entry::reads`).
//!
//! One namespace: the flow runner's ids come first. A native kernel whose id the runner already
//! lists at the pin (today `topological-sort`, a graph kernel there) stays the runner's, in the
//! catalogue and in a call. The runner's ids at the pin are the recorded
//! runner answer in `tools/research/vendor/algoglyph.pin.json`, which `algoglyph-pin bump` writes
//! with the gitlink and a test holds to it, so routing a call never boots npm to decide.
//!
//! The crate's other module, `fluids` (Stam's stable fluids), runs only its own seeded scenario
//! and declares no form for caller data, so it is not a catalogue entry. The crate algoglyph-cli
//! is a binary only (no library target); its catalogue is reached through the flow CLI.
use algoglyph_kernels::sorting::{self, prelude::{Entry, Item, Options, Outcome}};
use serde_json::{json, Map, Value};
use std::collections::BTreeSet;

/// The engine a native entry is listed with.
pub const ENGINE: &str = "native-rust";
/// The crate the native entries come from.
pub const CRATE: &str = "algoglyph-kernels";
/// The pin record: the pinned commit and the runner's catalogue at it (written by algoglyph-pin).
pub const PIN: &str = include_str!("../../vendor/algoglyph.pin.json");
/// The input keys every native kernel reads; the tunable options and `edges` only where its source
/// reads them.
const COMMON_KEYS: [&str; 3] = ["keys", "seed", "max_steps"];

/// The pin record, parsed; Null if the committed file is not JSON (a test refuses that).
pub fn pin() -> Value {
    serde_json::from_str(PIN).unwrap_or(Value::Null)
}

/// The commit AlgoGlyph is pinned at, as the pin record names it.
pub fn pinned_commit() -> Option<String> {
    pin()["commit"].as_str().map(str::to_string)
}

/// The ids a runner answer (`flow -- kernels`) lists.
fn ids(runner: &Value) -> BTreeSet<String> {
    runner.as_array().into_iter().flatten().filter_map(|k| k["id"].as_str().map(str::to_string)).collect()
}

/// The native kernels whose id the runner lists at the pin: they stay the runner's. Only the tests
/// read it; no binary reports it.
#[cfg(test)]
pub fn shadowed() -> Vec<&'static str> {
    let runner = ids(&pin()["kernels"]);
    sorting::REGISTRY.iter().map(|e| e.meta.id).filter(|id| runner.contains(*id)).collect()
}

/// The native kernel a call of `id` goes to: one of the registry the runner does not list at the pin.
fn native(id: &str) -> Option<&'static Entry> {
    sorting::find(id).filter(|_| !ids(&pin()["kernels"]).contains(id))
}

/// Whether a call of `id` is answered here rather than by the runner.
pub fn routes(id: &str) -> bool {
    native(id).is_some()
}

/// The input keys entry `e` reads.
fn input_keys(e: &Entry) -> Vec<&'static str> {
    let mut keys = COMMON_KEYS.to_vec();
    keys.extend(sorting::options_of(e));
    if e.reads.contains(&"edges") { keys.push("edges"); }
    keys
}

/// The input shape of `e`, in the runner's own notation (`{key: type, optional?: type}`).
fn input_shape(e: &Entry) -> String {
    let fields: Vec<String> = input_keys(e).iter().map(|k| match *k {
        "keys" => format!("keys: integer[] (32-bit, at most {})", sorting::MAX_N),
        "edges" => format!("edges?: [[from, to]] (indices into keys, at most {})", sorting::MAX_EDGES),
        "seed" => "seed?: integer".to_string(),
        other => format!("{other}?: integer (0 = the kernel's own default)"),
    }).collect();
    format!("{{{}}}", fields.join(", "))
}

/// One native kernel as a catalogue entry: the fields the runner's entries carry (id, engine,
/// input), and what the crate says of it.
fn entry(e: &Entry) -> Value {
    json!({"id": e.meta.id, "engine": ENGINE, "input": input_shape(e),
           "kind": e.meta.kind.as_str(), "stable": e.meta.stable.as_str(), "in_place": e.meta.in_place,
           "crate": format!("{CRATE} {}", sorting::VERSION), "source": format!("{:016x}", e.source)})
}

/// The native entries of a catalogue whose runner answered `runner`: every one routed here and
/// not listed by that runner (a checkout other than the pin may list more).
pub fn entries(runner: &Value) -> Vec<Value> {
    let listed = ids(runner);
    sorting::REGISTRY.iter().filter(|e| routes(e.meta.id) && !listed.contains(e.meta.id)).map(entry).collect()
}

/// The discovered catalogue: the runner's answer unchanged, then the native entries. Anything but
/// a list is returned as it is (the caller reports the runner's own answer).
pub fn merge(runner: Value) -> Value {
    match runner {
        Value::Array(mut list) => {
            let native = entries(&Value::Array(list.clone()));
            list.extend(native);
            Value::Array(list)
        }
        other => other,
    }
}

/// A refusal in the runner's form.
fn refused(why: String) -> Value {
    json!({"ok": false, "errors": [why]})
}

/// An unsigned integer field of the input, at most `max`; None when absent.
fn uint(input: &Map<String, Value>, key: &str, max: u64) -> Result<Option<u64>, String> {
    match input.get(key) {
        None | Some(Value::Null) => Ok(None),
        Some(v) => v.as_u64().filter(|n| *n <= max).map(Some).ok_or_else(|| format!("{key} must be an integer from 0 to {max}")),
    }
}

/// The caller's input to `e`, checked field by field, as the crate's run takes it.
fn parse(e: &Entry, input: &Value) -> Result<(Vec<Item>, Options), String> {
    let m = input.as_object().ok_or("the input must be a JSON object")?;
    let known = input_keys(e);
    if let Some(k) = m.keys().find(|k| !known.contains(&k.as_str())) {
        return Err(format!("{k} is not an input of {} (it reads: {})", e.meta.id, known.join(", ")));
    }
    let keys = m.get("keys").and_then(Value::as_array).ok_or("keys must be a list of integers")?;
    if keys.len() > sorting::MAX_N {
        return Err(format!("keys has {} items (limit {})", keys.len(), sorting::MAX_N));
    }
    let mut items = Vec::with_capacity(keys.len());
    for (i, k) in keys.iter().enumerate() {
        let key = k.as_i64().and_then(|n| i32::try_from(n).ok()).ok_or_else(|| format!("keys[{i}] must be a 32-bit integer"))?;
        items.push(Item::new(key, i as u32));
    }
    let mut opt = Options { trace: false, ..Options::default() };
    if let Some(seed) = uint(m, "seed", u64::MAX)? { opt.seed = seed; }
    if let Some(n) = uint(m, "max_steps", u32::MAX as u64)? { opt.max_steps = n as u32; }
    for name in sorting::options_of(e) {
        if let Some(n) = uint(m, name, u32::MAX as u64)? { opt.set_tunable(name, n as u32); }
    }
    if let Some(edges) = m.get("edges").filter(|v| !v.is_null()) {
        let list = edges.as_array().filter(|l| l.len() <= sorting::MAX_EDGES)
            .ok_or_else(|| format!("edges must be a list of at most {} pairs", sorting::MAX_EDGES))?;
        for (i, pair) in list.iter().enumerate() {
            let p: Vec<u32> = pair.as_array().map(|p| p.iter().filter_map(Value::as_u64).filter(|n| (*n as usize) < items.len()).map(|n| n as u32).collect()).unwrap_or_default();
            if p.len() != 2 || pair.as_array().map_or(0, Vec::len) != 2 {
                return Err(format!("edges[{i}] must be [from, to] with indices 0..{}", items.len()));
            }
            opt.edges.push((p[0], p[1]));
        }
    }
    Ok((items, opt))
}

/// Kernel `id` on `input`, in-process: the runner's answer form, `{ok: true, kernel, result,
/// counts}`, or `{ok: false, errors}` for an id not routed here, an input refused with its field
/// named, a run its step limit stopped, or an input outside the kernel's domain.
pub fn run(id: &str, input: &Value) -> Value {
    let Some(e) = native(id) else { return refused(format!("{id} is not a native kernel of {CRATE} at the pin")) };
    let (items, opt) = match parse(e, input) {
        Ok(v) => v,
        Err(why) => return refused(why),
    };
    let r = sorting::run_entry(e, items, &opt);
    match r.outcome {
        Outcome::Truncated => return refused(format!("{id} stopped at its step limit ({} steps)", opt.step_limit())),
        Outcome::Unsupported(why) => return refused(format!("{id}: {why}")),
        _ => {}
    }
    let c = r.counts;
    json!({"ok": true, "kernel": entry(e),
           "result": {"outcome": r.outcome.as_str(), "note": r.outcome.note(), "truncated": r.truncated,
                      "keys": r.output.iter().map(|x| x.key).collect::<Vec<_>>(),
                      "order": r.output.iter().map(|x| x.tag).collect::<Vec<_>>()},
           "counts": {"cmp": c.cmp, "swap": c.swap, "write": c.write, "read": c.read, "aux": c.aux,
                      "aux_writes": c.aux_writes, "rounds": c.rounds}})
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo() -> std::path::PathBuf {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..")
    }

    /// The first registry entry routed here that reads none of the tunable options or edges.
    fn plain() -> &'static Entry {
        sorting::REGISTRY.iter().find(|e| routes(e.meta.id) && e.reads.is_empty()).expect("a plain native kernel")
    }

    #[test]
    fn the_pin_record_names_the_gitlink_and_the_kernels_the_stack_needs() {
        let p = pin();
        assert_eq!(p["schema"], "algoglyph-pin/v1");
        let out = std::process::Command::new("git").args(["ls-files", "-s", "--", "tools/research/vendor/algoglyph"])
            .current_dir(repo()).output().expect("git");
        let index = String::from_utf8_lossy(&out.stdout);
        let gitlink = index.split_whitespace().nth(1).unwrap_or_default();
        assert!(index.starts_with("160000 "), "tools/research/vendor/algoglyph is a gitlink: {index:?}");
        assert_eq!(pinned_commit().as_deref(), Some(gitlink), "the pin record is stale: tools/research/algoglyph-pin bump");
        let listed = ids(&p["kernels"]);
        for need in p["needs"].as_array().expect("needs") {
            assert!(listed.contains(need.as_str().unwrap()), "the pinned runner lacks {need}");
        }
    }

    #[test]
    fn every_registry_kernel_is_native_unless_the_runner_lists_it() {
        let runner = ids(&pin()["kernels"]);
        let shadow = shadowed();
        for e in sorting::REGISTRY {
            assert_eq!(routes(e.meta.id), !runner.contains(e.meta.id), "{}", e.meta.id);
            assert_eq!(shadow.contains(&e.meta.id), runner.contains(e.meta.id));
        }
        assert!(sorting::REGISTRY.len() > shadow.len());
        assert!(!routes("knapsack-dp") && !routes("no-such-kernel"));
    }

    #[test]
    fn the_catalogue_is_the_runners_answer_then_every_native_entry() {
        let runner = pin()["kernels"].clone();
        let merged = merge(runner.clone());
        let list = merged.as_array().unwrap();
        let n = runner.as_array().unwrap().len();
        assert_eq!(&list[..n], runner.as_array().unwrap().as_slice(), "the runner's entries come first, unchanged");
        let native = &list[n..];
        assert_eq!(native.len(), sorting::REGISTRY.len() - shadowed().len());
        let all: BTreeSet<&str> = list.iter().filter_map(|k| k["id"].as_str()).collect();
        assert_eq!(all.len(), list.len(), "one namespace: no id twice");
        for k in native {
            assert_eq!(k["engine"], ENGINE);
            assert!(k["input"].as_str().unwrap().starts_with("{keys: integer[]"), "{k}");
            assert!(k["crate"].as_str().unwrap().starts_with(CRATE));
        }
        // A runner that lists a native id itself (a checkout other than the pin) keeps it.
        let id = plain().meta.id;
        let other = json!([{"id": id, "engine": "array"}]);
        assert!(entries(&other).iter().all(|k| k["id"] != id));
        assert_eq!(merge(json!({"ok": false})), json!({"ok": false}));
    }

    #[test]
    fn an_input_shape_names_only_the_options_the_kernel_reads() {
        let e = plain();
        assert_eq!(input_keys(e), COMMON_KEYS.to_vec());
        let tuned = sorting::REGISTRY.iter().find(|e| routes(e.meta.id) && e.reads.contains(&"k")).unwrap();
        assert!(input_shape(tuned).contains("k?: integer (0 = the kernel's own default)"));
        if let Some(t) = sorting::REGISTRY.iter().find(|e| e.reads.contains(&"edges")) {
            assert!(input_shape(t).contains("edges?: [[from, to]]"));
        }
    }

    #[test]
    fn a_native_kernel_answers_in_process_as_the_crate_runs_it() {
        let e = plain();
        let keys = [5, -3, 9, 0, 5, 2];
        let v = run(e.meta.id, &json!({"keys": keys, "seed": 7, "max_steps": 0}));
        assert_eq!(v["ok"], true, "{v}");
        assert_eq!(v["kernel"]["id"], e.meta.id);
        assert_eq!(v["kernel"]["engine"], ENGINE);
        let opt = Options { trace: false, seed: 7, ..Options::default() };
        let items: Vec<Item> = keys.iter().enumerate().map(|(i, k)| Item::new(*k, i as u32)).collect();
        let r = sorting::run_entry(e, items, &opt);
        assert_eq!(v["result"]["keys"], json!(r.output.iter().map(|x| x.key).collect::<Vec<_>>()));
        assert_eq!(v["result"]["order"], json!(r.output.iter().map(|x| x.tag).collect::<Vec<_>>()));
        assert_eq!(v["result"]["outcome"], r.outcome.as_str());
        assert_eq!(v["counts"]["cmp"], r.counts.cmp);
        if r.outcome == Outcome::Sorted {
            let mut want = keys.to_vec();
            want.sort();
            assert_eq!(v["result"]["keys"], json!(want));
        }
    }

    #[test]
    fn every_native_kernel_answers_the_shared_scenario() {
        for e in sorting::REGISTRY.iter().filter(|e| routes(e.meta.id)) {
            let v = run(e.meta.id, &json!({"keys": [3, 1, 2, 3, 0], "max_steps": 1_000_000}));
            assert!(v["ok"] == true || v["errors"].is_array(), "{}: {v}", e.meta.id);
            if v["ok"] == true {
                assert!(matches!(v["result"]["outcome"].as_str(), Some("sorted" | "not-a-sort")), "{}: {v}", e.meta.id);
            }
        }
    }

    #[test]
    fn a_tunable_option_reaches_the_kernel() {
        let e = sorting::REGISTRY.iter().find(|e| routes(e.meta.id) && e.reads.contains(&"k")).unwrap();
        let v = run(e.meta.id, &json!({"keys": [4, 3, 2, 1], "k": 3}));
        assert!(v["ok"] == true || v["errors"].is_array(), "{v}");
        let m = json!({"keys": [1], "k": 3});
        let (_, opt) = parse(e, &m).unwrap();
        assert_eq!(opt.tunable("k"), Some(3));
    }

    #[test]
    fn a_malformed_input_is_refused_with_the_field_named() {
        let id = plain().meta.id;
        let why = |input: Value| run(id, &input)["errors"][0].as_str().unwrap_or_default().to_string();
        assert!(why(json!([1, 2])).contains("JSON object"));
        assert!(why(json!({"keys": "nope"})).contains("keys must be a list"));
        assert!(why(json!({"keys": [1, 2.5]})).contains("keys[1]"));
        assert!(why(json!({"keys": [1, 4294967296i64]})).contains("keys[1]"));
        assert!(why(json!({"keys": [1], "seed": -1})).contains("seed must be"));
        assert!(why(json!({"keys": [1], "max_steps": 1u64 << 40})).contains("max_steps must be"));
        assert!(why(json!({"keys": [1], "k": 3})).contains("k is not an input"));
        assert!(why(json!({"keys": [1], "bogus": 1})).contains("it reads: keys, seed, max_steps"));
        let big = vec![0; sorting::MAX_N + 1];
        assert!(why(json!({"keys": big})).contains("limit"));
        assert!(run("knapsack-dp", &json!({}))["errors"][0].as_str().unwrap().contains("not a native kernel"));
        assert_eq!(run(id, &json!({"keys": [2, 1], "seed": null}))["ok"], true);
    }

    #[test]
    fn edges_are_checked_pair_by_pair() {
        // Only the topological sort reads edges, and the runner shadows it at the pin: the parser
        // is exercised on that entry directly.
        let Some(t) = sorting::REGISTRY.iter().find(|e| e.reads.contains(&"edges")) else { return };
        let (_, opt) = parse(t, &json!({"keys": [1, 2, 3], "edges": [[0, 1], [1, 2]]})).unwrap();
        assert_eq!(opt.edges, vec![(0, 1), (1, 2)]);
        assert!(parse(t, &json!({"keys": [1, 2], "edges": [[0, 5]]})).unwrap_err().contains("edges[0]"));
        assert!(parse(t, &json!({"keys": [1, 2], "edges": [[0, 1, 1]]})).unwrap_err().contains("edges[0]"));
        assert!(parse(t, &json!({"keys": [1, 2], "edges": [7]})).unwrap_err().contains("edges[0]"));
        assert!(parse(t, &json!({"keys": [1, 2], "edges": 7})).unwrap_err().contains("edges must be"));
        assert!(parse(t, &json!({"keys": [1, 2], "edges": null})).unwrap().1.edges.is_empty());
    }

    #[test]
    fn a_run_its_step_limit_stops_or_outside_its_domain_is_refused() {
        let mut stopped = false;
        let mut unsupported = false;
        let keys: Vec<i64> = (0..64).rev().collect();
        for e in sorting::REGISTRY.iter().filter(|e| routes(e.meta.id)) {
            let v = run(e.meta.id, &json!({"keys": keys, "max_steps": 1}));
            let why = v["errors"][0].as_str().unwrap_or_default();
            stopped |= why.contains("stopped at its step limit (1 steps)");
            let wide = run(e.meta.id, &json!({"keys": [i32::MIN, i32::MAX, 0]}));
            unsupported |= wide["ok"] == false && !wide["errors"][0].as_str().unwrap_or_default().contains("step limit");
        }
        assert!(stopped, "no native kernel stopped at a one-step limit");
        assert!(unsupported, "no native kernel refused a key range outside its domain");
    }
}
